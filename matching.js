function roleFromCounts(counts,answers){
  const high=Math.max(...counts);
  for(let q=answers.length-1;q>=0;q--)if(counts[answers[q]]===high)return answers[q];
}

function matchMoment(key,answers){
  const set=momentLibrary[key];
  if(!set||answers.length!==10)throw Error('十道题都答完后才能匹配场景');
  const counts=[0,0,0,0],affinity=[0,0,0,0];
  for(let q=0;q<10;q++){
    const a=answers[q];if(!Number.isInteger(a)||a<0||a>3)throw Error('答案超出选项范围');
    counts[a]++;affinity[a]+=set.pairs[a].cues[q];
  }
  const type=roleFromCounts(counts,answers),mix=set.mix;
  const [left,right]=mix.roles;
  const sharedLead=mix.roles.includes(type)&&Math.min(counts[left],counts[right])>=3&&Math.abs(counts[left]-counts[right])<=1
    &&counts.every((n,i)=>mix.roles.includes(i)||n<Math.min(counts[left],counts[right]));
  if(sharedLead&&mix.questions.every((qs,side)=>qs.some(q=>answers[q]===mix.roles[side]))){
    return {type,variant:2};
  }
  return {type,variant:Number(affinity[type]>0)};
}
function momentFor(item,match){
  const {type,variant}=match,set=momentLibrary[item.key],pair=set.pairs[type];
  const stem=variant===2?set.mix.stem:item.key+'-'+(variant?'portrait':'')+type;
  return {key:item.key,label:item.label,role:item.roles[type],type,variant,stem,
    title:variant===2?set.mix.title:pair.titles[variant],caption:variant===2?set.mix.caption:pair.captions[variant]};
}
function supportingAnswers(item,answers,match){
  const set=momentLibrary[item.key];
  if(match.variant===2)return set.mix.questions.map((qs,side)=>qs.find(i=>answers[i]===set.mix.roles[side]));
  const sign=match.variant?1:-1,cues=set.pairs[match.type].cues;
  return answers.map((a,i)=>i).filter(i=>answers[i]===match.type).sort((a,b)=>sign*(cues[b]-cues[a])||a-b).slice(0,2);
}
